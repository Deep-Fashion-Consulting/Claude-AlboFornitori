-- -----------------------------------------------------------------------------
-- Tracciamento delle sincronizzazioni
-- -----------------------------------------------------------------------------
CREATE TABLE ext.sync_run (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sorgente     varchar(20) NOT NULL,          -- 'SAP', 'ST3', 'ERP'
  entita       varchar(60) NOT NULL,          -- es. 'fatturato_passivo'
  avviato_il   timestamptz NOT NULL DEFAULT now(),
  terminato_il timestamptz,
  esito        varchar(10) NOT NULL DEFAULT 'IN_CORSO' CHECK (esito IN ('IN_CORSO', 'OK', 'ERRORE')),
  righe        integer,
  messaggio    text
);
CREATE INDEX ix_sync_run_entita ON ext.sync_run(entita, avviato_il DESC);
COMMENT ON TABLE ext.sync_run IS
  'Una riga per ogni esecuzione ETL. Fornisce la data "Dati aggiornati al" mostrata in UI.';

-- -----------------------------------------------------------------------------
-- Fatturato passivo / attivo (ex OCA.ANAGRAFICA.FORNITORE_FATTURATO_PASSIVO / _ATTIVO)
-- -----------------------------------------------------------------------------
CREATE TABLE ext.fatturato_passivo (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fornitore_id bigint   NOT NULL REFERENCES albo.fornitore(id),
  societa_id   integer  NOT NULL REFERENCES ref.societa(id),
  anno         smallint NOT NULL CHECK (anno BETWEEN 1900 AND 2100),
  valuta_id    integer  NOT NULL REFERENCES ref.valuta(id),
  totale       numeric(18,2) NOT NULL,
  totale_eur   numeric(18,2) NOT NULL,
  sync_run_id  bigint REFERENCES ext.sync_run(id),
  CONSTRAINT ux_fatt_passivo UNIQUE (fornitore_id, societa_id, anno, valuta_id)
);
CREATE INDEX ix_fatt_passivo_anno ON ext.fatturato_passivo(anno, fornitore_id);

CREATE TABLE ext.fatturato_attivo (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fornitore_id bigint   NOT NULL REFERENCES albo.fornitore(id),
  societa_id   integer  NOT NULL REFERENCES ref.societa(id),
  anno         smallint NOT NULL CHECK (anno BETWEEN 1900 AND 2100),
  valuta_id    integer  NOT NULL REFERENCES ref.valuta(id),
  totale       numeric(18,2) NOT NULL,
  totale_eur   numeric(18,2) NOT NULL,
  sync_run_id  bigint REFERENCES ext.sync_run(id),
  CONSTRAINT ux_fatt_attivo UNIQUE (fornitore_id, societa_id, anno, valuta_id)
);
CREATE INDEX ix_fatt_attivo_anno ON ext.fatturato_attivo(anno, fornitore_id);
COMMENT ON TABLE ext.fatturato_attivo IS
  '[H17] Struttura assunta simmetrica al passivo: nel legacy il fatturato attivo compare solo come filtro di ricerca.';

-- -----------------------------------------------------------------------------
-- Ordinato SAP / ST3 (ex OCA.ANAGRAFICA.FORNITORE_ORDINATO_SAP / _ST3)
-- -----------------------------------------------------------------------------
CREATE TABLE ext.ordinato_sap (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fornitore_id        bigint   NOT NULL REFERENCES albo.fornitore(id),
  societa_id          integer  NOT NULL REFERENCES ref.societa(id),
  ente_id             integer  REFERENCES ref.ente(id),
  cod_gruppo_acquisto varchar(20),
  anno                smallint NOT NULL CHECK (anno BETWEEN 1900 AND 2100),
  valuta_id           integer  NOT NULL REFERENCES ref.valuta(id),
  importo             numeric(18,2) NOT NULL,
  importo_eur         numeric(18,2),
  sync_run_id         bigint REFERENCES ext.sync_run(id)
);
CREATE INDEX ix_ord_sap_fornitore ON ext.ordinato_sap(fornitore_id, anno DESC);

CREATE TABLE ext.ordinato_st3 (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fornitore_id           bigint   NOT NULL REFERENCES albo.fornitore(id),
  societa_id             integer  NOT NULL REFERENCES ref.societa(id),
  ente_id                integer  REFERENCES ref.ente(id),
  classe_merceologica_id integer  REFERENCES ref.classe_merceologica(id),
  cod_gruppo_acquisto    varchar(20),
  tipo_ordine            varchar(30),
  anno                   smallint NOT NULL CHECK (anno BETWEEN 1900 AND 2100),
  valuta_id              integer  NOT NULL REFERENCES ref.valuta(id),
  importo                numeric(18,2) NOT NULL,
  importo_eur            numeric(18,2),
  sync_run_id            bigint REFERENCES ext.sync_run(id)
);
CREATE INDEX ix_ord_st3_fornitore ON ext.ordinato_st3(fornitore_id, anno DESC);
COMMENT ON COLUMN ext.ordinato_st3.tipo_ordine IS 'Filtro orderType di GetOrdersAndTurnover.';

-- -----------------------------------------------------------------------------
-- Pagamenti (ex OCA.ANAGRAFICA.FORNITORE_MOD_PAGAMENTO) - pagina Anagrafica_Bank
-- -----------------------------------------------------------------------------
CREATE TABLE ext.fornitore_modalita_pagamento (
  id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fornitore_id            bigint  NOT NULL REFERENCES albo.fornitore(id),
  societa_id              integer NOT NULL REFERENCES ref.societa(id),
  modalita_pagamento_id   integer REFERENCES ref.modalita_pagamento(id),
  condizione_pagamento_id integer REFERENCES ref.condizione_pagamento(id),
  iban                    varchar(34),
  sync_run_id             bigint REFERENCES ext.sync_run(id)
);
CREATE INDEX ix_mod_pag_fornitore ON ext.fornitore_modalita_pagamento(fornitore_id);

-- =============================================================================
-- AUDIT (ex TBL_TRACELOG / ScriviLogApplicativo)
-- =============================================================================
CREATE TABLE audit.log (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  occurred_at    timestamptz NOT NULL DEFAULT now(),
  utente_id      bigint,
  username       varchar(150),
  azione         varchar(60) NOT NULL,
  entita         varchar(60),
  entita_id      varchar(100),
  fornitore_id   bigint,
  ip             inet,
  correlation_id uuid,
  dettagli       jsonb
);
CREATE INDEX ix_audit_fornitore ON audit.log(fornitore_id, occurred_at DESC);
CREATE INDEX ix_audit_utente    ON audit.log(utente_id, occurred_at DESC);
CREATE INDEX ix_audit_azione    ON audit.log(azione, occurred_at DESC);
COMMENT ON TABLE audit.log IS
  'Log applicativo append-only. Volutamente senza FK, per non legare il log al ciclo di vita dei dati. '
  'Azioni tipiche: LOGIN, LOGIN_DENIED, SUPPLIER_VIEW, SUPPLIER_GENERAL_UPDATE, ...';
COMMENT ON COLUMN audit.log.dettagli IS 'Payload JSON della modifica (campi prima/dopo) quando utile.';
