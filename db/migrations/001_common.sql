-- -----------------------------------------------------------------------------
-- unaccent() non e'' IMMUTABLE e quindi non indicizzabile: wrapper immutabile.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION common.f_unaccent(text)
RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

-- Chiave di ricerca normalizzata (minuscolo, senza accenti, spazi compressi)
CREATE OR REPLACE FUNCTION common.f_search_key(text)
RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT regexp_replace(lower(common.f_unaccent($1)), '\s+', ' ', 'g') $$;

-- -----------------------------------------------------------------------------
-- Trigger generico per updated_at
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION common.trg_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- Applica il trigger updated_at a tutte le tabelle di uno schema che hanno la colonna.
-- Da richiamare a fine di ogni migrazione che crea tabelle con updated_at.
CREATE OR REPLACE FUNCTION common.attach_updated_at_triggers(p_schema text)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT c.table_name
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON t.table_schema = c.table_schema AND t.table_name = c.table_name
    WHERE c.table_schema = p_schema
      AND c.column_name = 'updated_at'
      AND t.table_type = 'BASE TABLE'
  LOOP
    EXECUTE format(
      'CREATE OR REPLACE TRIGGER trg_updated_at BEFORE UPDATE ON %I.%I
         FOR EACH ROW EXECUTE FUNCTION common.trg_set_updated_at()',
      p_schema, r.table_name);
  END LOOP;
END;
$$;

-- -----------------------------------------------------------------------------
-- Template delle tabelle di lookup.
-- Ogni lookup viene creata con: CREATE TABLE ref.x (LIKE common.lookup_template INCLUDING ALL)
-- In questo modo tutte le liste hanno la stessa forma e l'API puo' servirle in modo generico.
-- -----------------------------------------------------------------------------
CREATE TABLE common.lookup_template (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codice         varchar(30) UNIQUE,
  descrizione_it varchar(200) NOT NULL,
  descrizione_en varchar(200),
  ordine         smallint NOT NULL DEFAULT 0,
  attivo         boolean  NOT NULL DEFAULT true
);
COMMENT ON TABLE common.lookup_template IS
  'Template strutturale per le lookup; non contiene dati. GENERATED BY DEFAULT consente di importare gli ID legacy.';
