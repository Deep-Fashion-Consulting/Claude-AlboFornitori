-- Collegamenti tra fornitori
CREATE TABLE albo.fornitore_collegamento (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fornitore_da_id  bigint NOT NULL REFERENCES albo.fornitore(id) ON DELETE CASCADE,
  fornitore_a_id   bigint NOT NULL REFERENCES albo.fornitore(id) ON DELETE CASCADE,
  tipo             varchar(20) NOT NULL CHECK (tipo IN ('CONSOLIDATO', 'ALTERNATIVO', 'PADRE_FIGLIO')),
  attivo           boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint REFERENCES iam.utente(id),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint REFERENCES iam.utente(id),
  CONSTRAINT ck_collegamento_self CHECK (fornitore_da_id <> fornitore_a_id),
  CONSTRAINT ux_collegamento UNIQUE (fornitore_da_id, fornitore_a_id, tipo)
);
CREATE INDEX ix_collegamento_a ON albo.fornitore_collegamento(fornitore_a_id, tipo);
COMMENT ON TABLE albo.fornitore_collegamento IS
  'Ex TB_FORNITORE_COLLEGAMENTI. Semantica [H12 - confermata]: '
  'CONSOLIDATO  da = capogruppo, a = consolidato (il fatturato di "a" si somma a quello di "da"); '
  'ALTERNATIVO  a = fornitore alternativo di "da" (lettura inversa: "Fornitore alternativo di"); '
  'PADRE_FIGLIO relazione simmetrica: i due fornitori sono la stessa azienda nel tempo. '
  'Per PADRE_FIGLIO la coppia e'' salvata in forma canonica (id minore in fornitore_da_id) dal trigger '
  'trg_collegamento_canonico, cosi A-B e B-A non possono coesistere.';

-- Le relazioni simmetriche si salvano sempre con l'id minore in fornitore_da_id
CREATE OR REPLACE FUNCTION albo.trg_collegamento_canonico()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  tmp bigint;
BEGIN
  IF NEW.tipo = 'PADRE_FIGLIO' AND NEW.fornitore_da_id > NEW.fornitore_a_id THEN
    tmp := NEW.fornitore_da_id;
    NEW.fornitore_da_id := NEW.fornitore_a_id;
    NEW.fornitore_a_id := tmp;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_collegamento_canonico
  BEFORE INSERT OR UPDATE OF fornitore_da_id, fornitore_a_id, tipo ON albo.fornitore_collegamento
  FOR EACH ROW EXECUTE FUNCTION albo.trg_collegamento_canonico();

ALTER TABLE albo.fornitore_collegamento ADD CONSTRAINT ck_collegamento_simmetrico_canonico
  CHECK (tipo <> 'PADRE_FIGLIO' OR fornitore_da_id < fornitore_a_id);

