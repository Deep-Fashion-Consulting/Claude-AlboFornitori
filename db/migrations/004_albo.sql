CREATE TABLE albo.fornitore (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- Dati anagrafici "master" (in sola lettura nella UI legacy) ------------------
  ragione_sociale       varchar(255) NOT NULL,
  partita_iva           varchar(20),
  partita_iva_cee       varchar(20),
  codice_fiscale        varchar(20),
  telefono              varchar(40),
  fax                   varchar(40),
  iban                  varchar(34),
  cod_accorpamento      varchar(30),
  sostituito_da_id      bigint REFERENCES albo.fornitore(id),
  fonte_master          varchar(20) NOT NULL DEFAULT 'ERP',
  master_sync_at        timestamptz,

  -- Dati gestiti dall'Albo (ex clsPradaSupplier) -----------------------------
  denominazione_sociale varchar(255),
  sede_legale           varchar(500),
  data_inizio_attivita  date,
  data_inizio_rapporto  date,
  data_fine_rapporto    date,
