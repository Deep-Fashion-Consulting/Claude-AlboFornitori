--  TBL_Funzioni, TBL_MenuLingua, VIEW_AbilitazioniFunzioni, TB_ENTE_FORNITORE_UTENTE_VISIBILITA)
-- =============================================================================

CREATE TABLE iam.utente (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username          varchar(150) NOT NULL,
  oidc_subject      varchar(255) UNIQUE,
  legacy_id_persona integer UNIQUE,
  cognome           varchar(100) NOT NULL,
  nome              varchar(100) NOT NULL,
  email             varchar(254),
  lingua            char(2) NOT NULL DEFAULT 'IT' REFERENCES ref.lingua(codice),
  flag_lettura      boolean NOT NULL DEFAULT true,
  flag_scrittura    boolean NOT NULL DEFAULT false,
  attivo            boolean NOT NULL DEFAULT true,
  ultimo_accesso    timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_utente_username_lower CHECK (username = lower(username))
);
CREATE UNIQUE INDEX ux_utente_username ON iam.utente(username);
COMMENT ON TABLE  iam.utente IS
  'Utente applicativo. Sostituisce l''identita Windows (DOMAIN\user) con login OIDC.';
COMMENT ON COLUMN iam.utente.username IS
  'Username normalizzato in minuscolo senza dominio (come NormalizeDomainIdentity nel legacy).';
COMMENT ON COLUMN iam.utente.oidc_subject IS
  'Claim "sub" del provider OIDC; valorizzato al primo login riuscito.';
COMMENT ON COLUMN iam.utente.flag_lettura   IS 'Ex READ di TB_GSR_UTENZE ("Accesso ai dati").';
COMMENT ON COLUMN iam.utente.flag_scrittura IS 'Ex READ_WRITE di TB_GSR_UTENZE ("Aggiornamento dati").';

CREATE TABLE iam.gruppo (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codice      varchar(50) NOT NULL UNIQUE,
  descrizione varchar(200) NOT NULL,
  attivo      boolean NOT NULL DEFAULT true
);

CREATE TABLE iam.utente_gruppo (
  utente_id bigint  NOT NULL REFERENCES iam.utente(id) ON DELETE CASCADE,
  gruppo_id integer NOT NULL REFERENCES iam.gruppo(id) ON DELETE CASCADE,
  PRIMARY KEY (utente_id, gruppo_id)
);
CREATE INDEX ix_utente_gruppo_gruppo ON iam.utente_gruppo(gruppo_id);

-- -----------------------------------------------------------------------------
-- Funzioni applicative = voci di menu (albero AREA > MODULO > FUNZIONE)
-- -----------------------------------------------------------------------------
CREATE TABLE iam.funzione (
  id                         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id                  integer REFERENCES iam.funzione(id),
  codice                     varchar(60) NOT NULL UNIQUE,
  livello                    varchar(10) NOT NULL CHECK (livello IN ('AREA', 'MODULO', 'FUNZIONE')),
  route                      varchar(200),
  ordine                     smallint NOT NULL DEFAULT 0,
  richiede_fornitore         boolean NOT NULL DEFAULT true,
  richiede_ente_autorizzato  boolean NOT NULL DEFAULT false,
  legacy_id                  integer UNIQUE,
  attivo                     boolean NOT NULL DEFAULT true
);
CREATE INDEX ix_funzione_parent ON iam.funzione(parent_id);
COMMENT ON COLUMN iam.funzione.richiede_fornitore IS
  'Se true la voce compare solo con un fornitore selezionato. Nel legacy i moduli 700, 706, 710 sono sempre visibili.';
COMMENT ON COLUMN iam.funzione.richiede_ente_autorizzato IS
  'Se true la voce compare solo se l''utente ha almeno un ente autorizzato sul fornitore corrente (legacy: modulo 701).';
COMMENT ON COLUMN iam.funzione.route IS 'Percorso della route React, es. /fornitori/:id/anagrafica.';

CREATE TABLE iam.funzione_traduzione (
  funzione_id integer NOT NULL REFERENCES iam.funzione(id) ON DELETE CASCADE,
  lingua      char(2) NOT NULL REFERENCES ref.lingua(codice),
  descrizione varchar(200) NOT NULL,
  PRIMARY KEY (funzione_id, lingua)
);
COMMENT ON TABLE iam.funzione_traduzione IS
  'Ex TBL_MenuLingua/TBL_Funzioni. Se manca la traduzione si usa quella IT (TranslateFunction).';

CREATE TABLE iam.gruppo_funzione (
  gruppo_id   integer NOT NULL REFERENCES iam.gruppo(id) ON DELETE CASCADE,
  funzione_id integer NOT NULL REFERENCES iam.funzione(id) ON DELETE CASCADE,
  PRIMARY KEY (gruppo_id, funzione_id)
);
CREATE INDEX ix_gruppo_funzione_funzione ON iam.gruppo_funzione(funzione_id);
COMMENT ON TABLE iam.gruppo_funzione IS
  '[H6] Le funzioni si assegnano solo tramite gruppo. Se VIEW_AbilitazioniFunzioni prevede anche '
  'assegnazioni dirette all''utente, aggiungere iam.utente_funzione.';

-- -----------------------------------------------------------------------------
-- Visibilita' sugli enti
-- -----------------------------------------------------------------------------
CREATE TABLE iam.utente_ente (
  utente_id bigint  NOT NULL REFERENCES iam.utente(id) ON DELETE CASCADE,
  ente_id   integer NOT NULL REFERENCES ref.ente(id),
  PRIMARY KEY (utente_id, ente_id)
);
CREATE INDEX ix_utente_ente_ente ON iam.utente_ente(ente_id);
COMMENT ON TABLE iam.utente_ente IS
  'Enti su cui l''utente e'' abilitato (ex TB_ENTE_FORNITORE_UTENTE_VISIBILITA, lista "Enti abilitati").';

